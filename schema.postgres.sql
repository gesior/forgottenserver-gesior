DROP TRIGGER IF EXISTS ondelete_players ON players;
DROP FUNCTION IF EXISTS ondelete_players();

CREATE OR REPLACE FUNCTION ondelete_players()
RETURNS trigger AS $$
BEGIN
  UPDATE houses SET owner = 0 WHERE owner = OLD.id;
  RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER ondelete_players
BEFORE DELETE ON players
FOR EACH ROW EXECUTE FUNCTION ondelete_players();

DROP TRIGGER IF EXISTS oncreate_guilds ON guilds;
DROP FUNCTION IF EXISTS oncreate_guilds();

CREATE OR REPLACE FUNCTION oncreate_guilds()
RETURNS trigger AS $$
BEGIN
  INSERT INTO guild_ranks (name, level, guild_id) VALUES ('the Leader', 3, NEW.id);
  INSERT INTO guild_ranks (name, level, guild_id) VALUES ('a Vice-Leader', 2, NEW.id);
  INSERT INTO guild_ranks (name, level, guild_id) VALUES ('a Member', 1, NEW.id);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER oncreate_guilds
AFTER INSERT ON guilds
FOR EACH ROW EXECUTE FUNCTION oncreate_guilds();
